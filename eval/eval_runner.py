"""Retrieval evaluation: Recall@k and MRR over the validation pairs.

Usage:
    python -m eval.eval_runner --n 300
    python -m eval.eval_runner --n 300 --configs dense bm25 hybrid
    python -m eval.eval_runner --n 100 --configs hybrid rerank

===========================  READ THIS FIRST  ===============================
The pairs in data/processed/val_pairs.jsonl were generated by
scripts/make_pairs_pubmed.py, which samples sentences *out of* an abstract and
uses the abstract itself as the positive. Every query is therefore a verbatim
substring of its own gold document.

That means these numbers measure "can you find the document this sentence was
copied from" -- a near-duplicate detection task that strongly favours lexical
matching. They are a legitimate *regression* signal (a change that drops recall
here has probably broken something) but they are NOT evidence that the system
answers real user queries well, and BM25 scoring near-perfectly is expected
rather than impressive.

To measure real semantic search quality you need queries written independently
of the documents -- either human-written questions with judged relevant docs,
or an established benchmark such as BEIR/TREC-COVID or NFCorpus.
=============================================================================
"""
from __future__ import annotations

import argparse
import json
import random
import statistics
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

CAVEAT = """NOTE ON THESE NUMBERS
  Every query in val_pairs.jsonl is a verbatim sentence copied out of its own
  gold document (see scripts/make_pairs_pubmed.py). This is a near-duplicate
  detection task, not semantic search, and it structurally favours lexical
  matching -- BM25 scoring near 1.0 here is expected, not a sign it is the
  better retriever for real queries.
  Use these as a REGRESSION signal only. For true search quality, evaluate on
  independently written queries (BEIR / NFCorpus / TREC-COVID).
"""


def load_pairs(path: Path, n: int, seed: int) -> list[dict]:
    rows = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    random.Random(seed).shuffle(rows)
    return rows[:n]


def build_gold_map(corpus: list[dict]) -> dict[str, int]:
    return {(d.get("text") or "").strip(): i for i, d in enumerate(corpus)}


def metrics(ranks: list[int | None], ks=(1, 5, 10)) -> dict[str, float]:
    """ranks holds the 1-based rank of the gold doc, or None if it was missed."""
    out: dict[str, float] = {}
    n = len(ranks) or 1
    for k in ks:
        out[f"recall@{k}"] = sum(1 for r in ranks if r is not None and r <= k) / n
    out["mrr@10"] = sum(1.0 / r for r in ranks if r is not None and r <= 10) / n
    found = [r for r in ranks if r is not None]
    out["median_rank"] = statistics.median(found) if found else float("nan")
    return out


def evaluate(service, pairs, gold_map, config: str, top_k: int = 10) -> dict[str, float]:
    from src.app.core.config import settings

    original = (settings.hybrid_enabled, settings.hybrid_alpha, settings.rerank_enabled)
    hybrid, rerank = None, False

    if config == "dense":
        hybrid = False
    elif config == "bm25":
        hybrid = True
        settings.hybrid_alpha = 0.0  # pure lexical
    elif config.startswith("hybrid"):
        hybrid = True
        if ":" in config:  # e.g. hybrid:0.5
            settings.hybrid_alpha = float(config.split(":", 1)[1])
    elif config == "rerank":
        hybrid = True
        rerank = True
    else:
        raise ValueError(f"unknown config: {config}")

    ranks: list[int | None] = []
    latencies: list[float] = []
    skipped = 0

    try:
        for pair in pairs:
            gold = gold_map.get(pair["doc"].strip())
            if gold is None:
                skipped += 1
                continue
            t0 = time.perf_counter()
            hits = service.search(pair["query"], k=top_k, hybrid=hybrid, rerank=rerank)
            latencies.append((time.perf_counter() - t0) * 1000)
            rank = next((i for i, h in enumerate(hits, 1) if h["id"] == gold), None)
            ranks.append(rank)
    finally:
        settings.hybrid_enabled, settings.hybrid_alpha, settings.rerank_enabled = original

    result = metrics(ranks)
    result["p50_ms"] = statistics.median(latencies) if latencies else float("nan")
    result["p95_ms"] = (
        sorted(latencies)[int(len(latencies) * 0.95)] if len(latencies) > 20 else float("nan")
    )
    result["n"] = len(ranks)
    result["skipped"] = skipped
    return result


def main() -> None:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--pairs", default=str(ROOT / "data/processed/val_pairs.jsonl"))
    ap.add_argument("--n", type=int, default=300, help="number of queries to evaluate")
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--top-k", type=int, default=10)
    ap.add_argument(
        "--configs",
        nargs="+",
        default=["dense", "bm25", "hybrid:0.5", "hybrid:0.7"],
        help="any of: dense, bm25, hybrid, hybrid:<alpha>, rerank",
    )
    ap.add_argument("--json-out", default=None, help="write results to this JSON file")
    args = ap.parse_args()

    pairs_path = Path(args.pairs)
    if not pairs_path.exists():
        raise SystemExit(f"No validation pairs at {pairs_path}")

    from src.app.services.retriever import search_service

    print("Loading index...", flush=True)
    t0 = time.perf_counter()
    search_service.ensure_loaded()
    print(f"Loaded in {time.perf_counter() - t0:.1f}s\n", flush=True)

    corpus = search_service._corpus  # noqa: SLF001 -- eval script, internal access is fine
    gold_map = build_gold_map(corpus)
    pairs = load_pairs(pairs_path, args.n, args.seed)

    print(CAVEAT)
    header = f"{'config':<14}{'R@1':>8}{'R@5':>8}{'R@10':>8}{'MRR@10':>9}{'p50 ms':>9}{'p95 ms':>9}"
    print(header)
    print("-" * len(header))

    results = {}
    for config in args.configs:
        r = evaluate(search_service, pairs, gold_map, config, top_k=args.top_k)
        results[config] = r
        print(
            f"{config:<14}{r['recall@1']:>8.3f}{r['recall@5']:>8.3f}{r['recall@10']:>8.3f}"
            f"{r['mrr@10']:>9.3f}{r['p50_ms']:>9.1f}{r['p95_ms']:>9.1f}"
        )

    print(f"\nEvaluated {args.n} queries against {len(corpus)} documents.")

    if args.json_out:
        Path(args.json_out).write_text(json.dumps(results, indent=2), encoding="utf-8")
        print(f"Wrote {args.json_out}")


if __name__ == "__main__":
    main()
